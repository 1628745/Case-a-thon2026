"""Build the browser copy of the pipeline for docs/lab.html.

python scripts/build_lab.py
  docs/py/guardlab/*.py   copies of src core modules ("from src.x" -> "from .x"); never edit by hand
  docs/py/lab_config.json config.yaml as JSON + hashes + file list for docs/lab-worker.js
  docs/data/lab_sample.csv SYNTHETIC LaDe-shaped sample (scripts/make_sample.py), when that script exists
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.common import config_hash, load_config  # noqa: E402

MODULES = ["common", "prep", "degrade", "guard", "model", "audit", "walkforward", "lab"]
OUT = os.path.join(ROOT, "docs", "py", "guardlab")
HEADER = "# GENERATED by scripts/build_lab.py from src/{name}.py. Do not edit; edit src/ and rebuild.\n"


def transform(name, text):
    text = re.sub(r"\bfrom src\.(\w+) import", r"from .\1 import", text)
    text = re.sub(r"\bfrom src import", "from . import", text)
    return HEADER.format(name=name) + text


def expected_files():
    out = {}
    for m in MODULES:
        with open(os.path.join(ROOT, "src", m + ".py")) as f:
            out[m + ".py"] = transform(m, f.read())
    out["__init__.py"] = HEADER.format(name="__init__") + '"""Browser build of the Shelf-Life Guard pipeline (see src/)."""\n'
    return out


def lab_config():
    cfg = load_config()
    return {"config": cfg, "config_hash": config_hash(cfg), "guard_hash": config_hash(cfg["guard"]),
            "guard_tag": "guard-v1-frozen", "py_files": sorted(expected_files())}


def main():
    os.makedirs(OUT, exist_ok=True)
    for fn, text in expected_files().items():
        with open(os.path.join(OUT, fn), "w") as f:
            f.write(text)
    with open(os.path.join(ROOT, "docs", "py", "lab_config.json"), "w") as f:
        json.dump(lab_config(), f, indent=1)
        f.write("\n")
    print(f"wrote {len(expected_files())} files to {os.path.relpath(OUT, ROOT)} and docs/py/lab_config.json")
    sample = os.path.join(ROOT, "scripts", "make_sample.py")
    if os.path.exists(sample):
        sys.path.insert(0, os.path.dirname(sample))
        import make_sample
        make_sample.main()


if __name__ == "__main__":
    main()
